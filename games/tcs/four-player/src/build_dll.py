#!/usr/bin/env python3
"""Build the TCS PC four-player patch as dinput8.dll.

Usage:
    python build_dll.py <unpacked LEGOStarWarsSaga.exe> <output dinput8.dll> [--research]

The unpacked executable (SteamStub removed, e.g. with Steamless) is only read
at build time, to check and record the original bytes of every patched
location. The resulting DLL works with the normal Steam executable: players
copy it into the game folder and change nothing else.

Requires GNU binutils for i386 (as, ld, objcopy, nm; see build.py) and LLVM
(clang, lld-link, llvm-dlltool). Set LLVM_PREFIX if the LLVM tools are not on
PATH under those names.
"""
import os, struct, subprocess, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
BASE_A = 0x02A8E000
DELTA = 0x01230000          # low 16 bits zero: a moved field changes bytes 2..3 only
BASE_B = BASE_A + DELTA

IAT_HOOK_VA = 0x7511A4      # KERNEL32!GetSystemTimeAsFileTime, first call after OEP
DECRYPT_CHECK_VA = 0x6F1668  # __security_init_cookie, the caller of that import
IMAGE_CHECK_VA = 0x400110    # PE TimeDateStamp (unencrypted header)
MOD_VERSION = "v0.48"


def fields(a, b, delta_ok):
    """Offsets of 32-bit fields that differ between builds a and b."""
    out, i = {}, 0
    while i < len(a):
        if a[i] == b[i]:
            i += 1
            continue
        j = i - 2
        va, vb = struct.unpack_from("<I", a, j)[0], struct.unpack_from("<I", b, j)[0]
        dlt = (vb - va) & 0xFFFFFFFF
        if dlt not in delta_ok:
            sys.exit("cannot classify changed field at +0x%X (delta 0x%X)" % (j, dlt))
        out[j] = delta_ok[dlt]
        i = j + 4
    return out


def c_bytes(name, data):
    rows = ["    " + ", ".join("0x%02x" % x for x in data[k:k + 16]) for k in range(0, len(data), 16)]
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, max(len(data), 1), ",\n".join(rows) or "0")


def c_u32(name, vals):
    body = ", ".join("0x%x" % v for v in vals) or "0"
    return "static const unsigned int %s[%d] = { %s };\n" % (name, max(len(vals), 1), body)


def generate(exe, research):
    d0 = bytearray(open(exe, "rb").read())
    _pe, _opt, _sect, secs, fo = build.check_input(d0)

    def va_of(off):
        for _n, sva, vsz, rsz, roff in secs:
            if roff <= off < roff + min(vsz, rsz):
                return off - roff + sva + build.IMG
        raise SystemExit("file offset 0x%X outside sections" % off)

    code_a, sym_a = build.assemble(research, BASE_A)
    code_b, sym_b = build.assemble(research, BASE_B)
    if len(code_a) != len(code_b):
        sys.exit("hook code size depends on its base address")
    blob_a, blob_b = build.mod_section(code_a), build.mod_section(code_b)
    bf = fields(blob_a, blob_b, {DELTA: "abs", (-DELTA) & 0xFFFFFFFF: "rel"})
    blob0 = bytearray(blob_a)
    for off, kind in bf.items():
        v = struct.unpack_from("<I", blob0, off)[0]
        struct.pack_into("<I", blob0, off, (v - BASE_A if kind == "abs" else v + BASE_A) & 0xFFFFFFFF)
    init_len = 0x100 + len(code_a)
    for off in bf:
        if off + 4 > init_len:
            sys.exit("relocated field outside initialised data")

    da, db = bytearray(d0), bytearray(d0)
    build.patch_code(da, fo, BASE_A, sym_a)
    build.patch_code(db, fo, BASE_B, sym_b)
    cf = fields(da, db, {DELTA: "abs"})
    touched = {i for i in range(len(d0)) if d0[i] != da[i]}
    for off in cf:
        touched.update(range(off, off + 4))

    # contiguous records, at most 64 bytes, never splitting a field
    recs, cur = [], None
    for off in sorted(touched):
        if cur and off == cur[0] + cur[1] and cur[1] < 64:
            cur[1] += 1
        else:
            cur = [off, 1]
            recs.append(cur)
    orig, new, fix, table = bytearray(), bytearray(), [], []
    for start, n in recs:
        fx = [o - start for o in cf if start <= o < start + n]
        for o in fx:
            if o + 4 > n:
                sys.exit("record split inside a relocated field")
        seg = bytearray(da[start:start + n])
        for o in fx:
            v = struct.unpack_from("<I", seg, o)[0]
            struct.pack_into("<I", seg, o, (v - BASE_A) & 0xFFFFFFFF)
        table.append((va_of(start), len(orig), n, len(fix), len(fx)))
        orig += d0[start:start + n]
        new += seg
        fix += fx

    h = ["/* generated by build_dll.py - do not edit */",
         '#define MOD_VERSION "%s%s"' % (MOD_VERSION, "-research" if research else ""),
         "#define IAT_HOOK_VA 0x%xu" % IAT_HOOK_VA,
         "#define DECRYPT_CHECK_VA 0x%xu" % DECRYPT_CHECK_VA,
         "#define IMAGE_CHECK_VA 0x%xu" % IMAGE_CHECK_VA,
         "#define IMAGE_CHECK_VALUE 0x%xu" % struct.unpack_from("<I", d0, IMAGE_CHECK_VA - build.IMG)[0],
         "#define MOD_SIZE 0x%x" % build.M_SIZE,
         "#define RING_FUNC_OFF 0x1f40",
         "#define WATCH_FUNC_OFF 0x1f4c",
         "#define F2_FUNC_OFF 0x1f5c",
         "#define MOD_INIT_LEN %d" % init_len,
         "#define N_BLOB_ABS %d" % sum(1 for k in bf.values() if k == "abs"),
         "#define N_BLOB_REL %d" % sum(1 for k in bf.values() if k == "rel"),
         "#define N_RECORDS %d" % len(table),
         "struct rec { unsigned int va; unsigned short off, len, fix, nfix; };",
         c_bytes("decrypt_check", d0[fo(DECRYPT_CHECK_VA):fo(DECRYPT_CHECK_VA) + 16]),
         c_bytes("mod_init", blob0[:init_len]),
         c_u32("blob_abs", sorted(o for o, k in bf.items() if k == "abs")),
         c_u32("blob_rel", sorted(o for o, k in bf.items() if k == "rel")),
         c_bytes("patch_orig", orig),
         c_bytes("patch_new", new),
         "static const unsigned char patch_fix[%d] = { %s };" % (max(len(fix), 1), ", ".join(map(str, fix)) or "0"),
         "static const struct rec records[%d] = {" % len(table)]
    h += ["    { 0x%x, %d, %d, %d, %d }," % t for t in table]
    h.append("};\n")
    model = dict(blob0=blob0, init_len=init_len, bf=bf, table=table, orig=orig, new=new, fix=fix)
    return "\n".join(h), model


def tool(name):
    return os.environ.get("LLVM_PREFIX", "") + name


def compile_dll(header, out):
    tmp = tempfile.mkdtemp()
    open(os.path.join(tmp, "patchdata.h"), "w").write(header)
    dlldir = os.path.join(HERE, "dll")
    libs = []
    for lib, funcs in (("kernel32", ["VirtualAlloc@16", "VirtualProtect@16", "GetCurrentProcess@0",
                                     "FlushInstructionCache@12", "GetSystemDirectoryA@8",
                                     "LoadLibraryA@4", "GetProcAddress@8",
                                     "DisableThreadLibraryCalls@4", "GetModuleHandleA@4",
                                     "GetModuleFileNameA@12", "CreateFileA@28", "WriteFile@20",
                                     "CloseHandle@4", "AddVectoredExceptionHandler@8",
                                     "GetFileAttributesA@4", "CreateDirectoryA@8", "ReadFile@20",
                                     "FindFirstFileA@8", "FindNextFileA@8", "FindClose@4",
                                     "VirtualFree@12", "GetCurrentProcessId@0", "GetCurrentThreadId@0", "Sleep@4", "GetTickCount@0", "CreateThread@24", "OpenThread@12", "SuspendThread@4", "ResumeThread@4", "GetThreadContext@8"]),
                       ("user32", ["MessageBoxA@16", "GetAsyncKeyState@4", "GetForegroundWindow@0",
                                   "GetWindowThreadProcessId@8", "GetRawInputDeviceList@12", "GetRawInputDeviceInfoA@16"])):
        dfile = os.path.join(tmp, lib + ".def")
        open(dfile, "w").write("LIBRARY %s.dll\nEXPORTS\n%s\n" % (lib, "\n".join(funcs)))
        lfile = os.path.join(tmp, lib + ".lib")
        subprocess.check_call([tool("llvm-dlltool"), "-m", "i386", "-k", "-d", dfile, "-l", lfile])
        libs.append(lfile)
    obj = os.path.join(tmp, "loader.obj")
    subprocess.check_call([tool("clang"), "--target=i686-pc-windows-msvc", "-O2", "-c",
                           "-ffreestanding", "-fno-builtin", "-fno-stack-protector",
                           "-mno-stack-arg-probe", "-Wall", "-I", tmp,
                           "-o", obj, os.path.join(dlldir, "loader.c")])
    subprocess.check_call([tool("lld-link"), "/nologo", "/dll", "/machine:x86", "/nodefaultlib",
                           "/entry:DllMain", "/safeseh:no", "/def:" + os.path.join(dlldir, "dinput8.def"),
                           "/out:" + out, obj] + libs)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    header, _model = generate(sys.argv[1], "--research" in sys.argv[3:])
    compile_dll(header, sys.argv[2])
    print("wrote", sys.argv[2])


if __name__ == "__main__":
    main()
